// Package render turns the ledger into the read-only files agents and
// humans read: DECISIONS.md and contracts/<name> at their head revisions.
package render

import (
	"fmt"
	"slices"
	"strings"
	"time"

	"agentbus/internal/bus"
)

const header = "<!-- Generated by agent-bus from the ledger. Do not edit; changes go through the protocol. -->\n\n"

// Files returns path → content for every rendered file.
func Files(b *bus.Bus) (map[string]string, error) {
	contracts, err := b.Contracts()
	if err != nil {
		return nil, err
	}
	files := map[string]string{}
	for _, c := range contracts {
		full, err := b.Contract(c.Name, -1)
		if err != nil {
			return nil, err
		}
		files["contracts/"+c.Name] = full.Content
	}
	decisions, err := Decisions(b, contracts)
	if err != nil {
		return nil, err
	}
	files["DECISIONS.md"] = decisions
	return files, nil
}

// Decisions renders DECISIONS.md: open threads first, then decided ones,
// newest first, each with its diff and how it was reached.
func Decisions(b *bus.Bus, contracts []bus.Contract) (string, error) {
	threads, err := b.Threads()
	if err != nil {
		return "", err
	}
	var sb strings.Builder
	sb.WriteString(header)
	sb.WriteString("# Decisions\n\n")
	sb.WriteString("| Contract | Rev | Owner |\n|---|---|---|\n")
	for _, c := range contracts {
		fmt.Fprintf(&sb, "| `contracts/%s` | %d | %s |\n", c.Name, c.Rev, c.Owner)
	}

	var open, decided []bus.Thread
	for _, th := range threads {
		if th.State == bus.StateDecided {
			decided = append(decided, th)
		} else {
			open = append(open, th)
		}
	}

	if len(open) > 0 {
		sb.WriteString("\n## In negotiation\n\n")
		for _, th := range open {
			fmt.Fprintf(&sb, "- **%s** `%s` — %s", th.Title, th.ID, th.State)
			if th.Contract != "" {
				fmt.Fprintf(&sb, " on `%s`", th.Contract)
			}
			if th.AwaitingHuman != "" {
				fmt.Fprintf(&sb, " (waiting on %s's human)", th.AwaitingHuman)
			}
			if th.Blocking {
				sb.WriteString(" · blocking")
			}
			sb.WriteString("\n")
		}
	}

	sb.WriteString("\n## Decided\n")
	if len(decided) == 0 {
		sb.WriteString("\nNothing decided yet.\n")
	}
	for _, th := range decided {
		_, evs, err := b.Thread(th.ID)
		if err != nil {
			return "", err
		}
		writeDecided(&sb, th, evs)
	}
	return sb.String(), nil
}

func writeDecided(sb *strings.Builder, th bus.Thread, evs []bus.Event) {
	i := slices.IndexFunc(evs, func(e bus.Event) bool { return e.Type == bus.Decided })
	if i < 0 {
		return
	}
	dec := evs[i]
	chosen := slices.IndexFunc(evs, func(e bus.Event) bool { return e.Seq == th.DecidedSeq })

	fmt.Fprintf(sb, "\n### %s\n\n", th.Title)
	fmt.Fprintf(sb, "- **Thread:** `%s`\n", th.ID)
	fmt.Fprintf(sb, "- **Contract:** `%s` → rev %d\n", dec.Contract, *dec.Rev)
	fmt.Fprintf(sb, "- **Decided:** %s, resolved by %s\n", time.UnixMilli(dec.TS).UTC().Format("2006-01-02 15:04 UTC"), th.ResolvedBy)
	if chosen >= 0 {
		p := evs[chosen]
		fmt.Fprintf(sb, "- **Winning proposal:** #%d by %s — %s\n", p.Seq, p.From, oneLine(p.Body))
		if p.MandateRef != "" {
			fmt.Fprintf(sb, "- **Mandate:** %s\n", oneLine(p.MandateRef))
		}
	}
	sb.WriteString("\n<details><summary>How it was reached</summary>\n\n")
	for _, e := range evs {
		if e.Type == bus.Decided {
			continue
		}
		fmt.Fprintf(sb, "- #%d %s %s", e.Seq, e.Type, e.From)
		if e.To != "" {
			fmt.Fprintf(sb, " → %s", e.To)
		}
		if e.Body != "" {
			fmt.Fprintf(sb, ": %s", oneLine(e.Body))
		}
		sb.WriteString("\n")
	}
	sb.WriteString("\n</details>\n\n```diff\n")
	sb.WriteString(strings.TrimRight(dec.Diff, "\n"))
	sb.WriteString("\n```\n")
}

func oneLine(s string) string {
	return strings.Join(strings.Fields(s), " ")
}
